#!/usr/bin/env node
"use strict";
// Liminal's WebAssembly TeX runtime: the subset of Colophon's runtime that
// Liminal's documents open (tools/native-tex/runtime.json), delivered from
// Colophon's release archive into a local cache and staged into dist/ by
// tools/build.js. docs/printing.md explains the design.
//
//   node tools/native-tex.js fetch      # download and verify the subset into the cache (once)
//   node tools/native-tex.js check      # is the subset in the cache?
//   node tools/native-tex.js derive --full ../colophon/runtime/<id>.json [--archive FILE]
//                                       # re-derive the subset from what the engines open
//
// The cache is ${LIMINAL_NATIVE_TEX_CACHE:-${XDG_CACHE_HOME:-~/.cache}/liminal/native-tex}.
// A build without the runtime still succeeds and the page says PDF generation
// is unavailable; with LIMINAL_REQUIRE_NATIVE_TEX=1 (set in CI) it fails.
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const R = require("./vendor/colophon/runtime");

const ROOT = path.resolve(__dirname, "..");
const MANIFEST = path.join(ROOT, "tools/native-tex/runtime.json");
const CONFIG = "native-tex/config.js";

function cache() {
  return process.env.LIMINAL_NATIVE_TEX_CACHE || path.join(process.env.XDG_CACHE_HOME || path.join(os.homedir(), ".cache"), "liminal", "native-tex");
}
const required = () => process.env.LIMINAL_REQUIRE_NATIVE_TEX === "1";
const manifest = () => R.load(MANIFEST);

// Stages the runtime into dist and writes dist/native-tex/config.js, which
// tells the page where the runtime is, or that it is unavailable.
function stage(dist) {
  let config = null, reason = null;
  try {
    const staged = R.stage(manifest(), { cache: cache(), site: dist });
    config = { id: staged.id, url: staged.runtimePath, sha256: staged.sha256, bytes: staged.bytes, notices: "native-tex/" + staged.id + "/" };
  } catch (error) {
    if (!(error instanceof R.RuntimeUnavailable) || required()) throw error;
    reason = error.message;
  }
  fs.mkdirSync(path.join(dist, "native-tex"), { recursive: true });
  fs.writeFileSync(path.join(dist, CONFIG), "/* Generated by tools/build.js: the WebAssembly TeX runtime for Generate PDF, or null when this build has none. */\n" +
    "window.LiminalNativeTeXRuntime = " + JSON.stringify(config) + ";\n");
  return { config, reason };
}

// A typesetting failure with the log lines that explain it.
function explain(error, name) {
  const lines = String(error.log || "").split("\n");
  const found = lines.flatMap((line, i) => /^!|Missing character|Font shape|not loadable|not found/.test(line) ? lines.slice(i, i + 3) : []);
  error.message = name + ": " + error.message + (found.length ? "\n  " + found.slice(0, 24).join("\n  ") : "");
  return error;
}

// Typesets the corpus against the full runtime with tracing, and writes the
// subset of files the engines opened.
async function derive(fullPath, options = {}) {
  const harness = require("./vendor/colophon/harness");
  const runner = require("../src/vendor/colophon/native-tex.js");
  const corpus = require("./lib/pdf-corpus");
  const full = R.load(fullPath);
  const fullCache = options.cache || path.join(cache(), "full");
  await R.hydrate(full, { cache: fullCache, archive: options.archive, fetch: !options.archive, keepArchive: true, log: console.error });
  const site = fs.mkdtempSync(path.join(os.tmpdir(), "liminal-native-tex-"));
  try {
    const staged = R.stage(full, { cache: fullCache, site });
    const traces = { pdflatex: new Set(), xelatex: new Set() };
    for (const item of corpus.documents()) {
      const started = Date.now();
      const result = await harness.generate({ runner, site, runtimePath: staged.runtimePath, engine: item.document.engine, trace: true,
        files: [{ path: "main.tex", data: item.document.tex }], entrypoint: "main.tex" }).catch(error => { throw explain(error, item.name); });
      result.trace.forEach(key => traces[item.document.engine].add(key));
      console.error(item.name + ": " + item.document.engine + ", " + result.trace.length + " files, " + ((Date.now() - started) / 1000).toFixed(1) + " s");
    }
    const subset = R.subset(full, { pdflatex: [...traces.pdflatex].sort(), xelatex: [...traces.xelatex].sort() },
      "Files opened while typesetting tools/lib/pdf-corpus.js (node tools/native-tex.js derive).");
    fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
    fs.writeFileSync(MANIFEST, JSON.stringify(subset, null, 1) + "\n");
    return R.summary(subset);
  } finally { fs.rmSync(site, { recursive: true, force: true }); }
}

async function main(argv) {
  const command = argv[0];
  const option = name => { const i = argv.indexOf(name); return i > 0 ? argv[i + 1] : undefined; };
  if (command === "fetch") {
    console.log(JSON.stringify(await R.hydrate(manifest(), { cache: cache(), fetch: true, archive: option("--archive"), log: console.error })));
  } else if (command === "check") {
    const missing = R.missing(manifest(), cache()).size;
    console.log(JSON.stringify({ runtime: manifest().id, cache: cache(), missing }));
    return missing ? 1 : 0;
  } else if (command === "derive") {
    if (!option("--full")) throw new Error("derive needs --full <colophon>/runtime/<id>.json");
    console.log(JSON.stringify(await derive(option("--full"), { archive: option("--archive") }), null, 2));
  } else if (command === "summary") {
    console.log(JSON.stringify(R.summary(manifest()), null, 2));
  } else {
    throw new Error("usage: native-tex.js fetch [--archive FILE] | check | summary | derive --full FILE [--archive FILE]");
  }
  return 0;
}

module.exports = { MANIFEST, CONFIG, cache, required, manifest, stage, derive, explain };

if (require.main === module) {
  main(process.argv.slice(2)).then(code => { process.exitCode = code; }, error => { console.error(error.message); process.exitCode = 1; });
}
